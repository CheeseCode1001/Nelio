"""Exports icons, navigation icons and illustrations from the design generator into packages/ui.

Run from the repository root:  python -I packages/ui/scripts/export_design_assets.py
The generator in docs/design/E_hifi/generator is the source of truth; never edit the outputs by hand.
"""
import io, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
GEN = os.path.join(ROOT, "docs", "design", "E_hifi", "generator")
OUT = os.path.join(ROOT, "packages", "ui", "src", "generated")
SVG_DIR = os.path.join(ROOT, "packages", "ui", "illustrations")
sys.path.insert(0, GEN)

# illus.py only needs three names from lib2, which itself reads files from the designer's machine.
# Provide them directly so the export runs anywhere. Entrance animation is added in React (GSAP), not here.
import html, types  # noqa: E402
_lib2 = types.ModuleType("lib2")
_lib2.OL = "#0B0B14"
_lib2.A = lambda *a, **k: ""
_lib2.e = lambda s: html.escape(str(s), quote=True)
sys.modules["lib2"] = _lib2
import icons, illus  # noqa: E402

def write(path, text):
    io.open(path, "w", encoding="utf-8", newline="\n").write(text)

head = "// Generated by packages/ui/scripts/export_design_assets.py from docs/design/E_hifi/generator. Do not edit.\n"
write(os.path.join(OUT, "icons.ts"), head + "export const ICON_PATHS = " + json.dumps(icons.IC, indent=1, ensure_ascii=False) + " as const;\nexport type IconName = keyof typeof ICON_PATHS;\n")

ills = {}
for name, (fn, label) in illus.L.items():
    inner = fn()
    ills[name] = {"label": label, "inner": inner}
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" role="img" aria-label="{label}" viewBox="0 0 240 180">{inner}</svg>\n'
    write(os.path.join(SVG_DIR, name + ".svg"), svg)
write(os.path.join(OUT, "illustrations.ts"), head + "export const ILLUSTRATIONS = " + json.dumps(ills, indent=1, ensure_ascii=False) + " as const;\nexport type IllustrationName = keyof typeof ILLUSTRATIONS;\n")

try:
    import navicons
    data = {k: ({n: list(t) if isinstance(t, tuple) else t for n, t in v.items()}) for k, v in vars(navicons).items() if k.isupper() and isinstance(v, dict)}
    write(os.path.join(OUT, "navicons.ts"), head + "export const NAV_ICONS = " + json.dumps(data, indent=1, ensure_ascii=False) + " as const;\n")
    print("navicons:", {k: len(v) for k, v in data.items()})
except Exception as ex:  # reported, not hidden
    print("navicons export failed:", ex)

print("icons:", len(icons.IC), "illustrations:", len(ills))
bad = [n for n, v in ills.items() if re.search(r"gradient", v["inner"], re.I)]
print("illustrations containing a gradient:", bad)
