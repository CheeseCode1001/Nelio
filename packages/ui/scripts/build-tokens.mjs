// Generates packages/ui/src/tokens.css from docs/design/H_handoff/tokens.json (the single source, handoff §6.1).
// Run: pnpm tokens
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const tokens = JSON.parse(readFileSync(join(root, "docs/design/H_handoff/tokens.json"), "utf8"));

// token key -> CSS variable name
const NAMES = {
  bg: "bg", s1: "s1", s2: "s2", s3: "s3", bd: "bd", tx: "tx", mu: "mu",
  acc: "acc", onacc: "on-acc", accT: "acc-t", accTx: "acc-tx", ink: "ink", onink: "on-ink",
  lime: "lime", limeT: "lime-t", limeTx: "lime-tx", ai: "ai", aiT: "ai-t", aiTx: "ai-tx",
  ok: "ok", okT: "ok-t", okTx: "ok-tx", warn: "warn", warnT: "warn-t", warnTx: "warn-tx",
  err: "err", errT: "err-t", errTx: "err-tx", yellow: "yellow", cyan: "cyan", orange: "orange", pink: "pink", shadow: "shadow",
};

const block = (theme) =>
  Object.entries(NAMES)
    .map(([k, v]) => {
      if (!(k in theme)) throw new Error(`tokens.json is missing "${k}"`);
      return `  --n-${v}: ${theme[k]};`;
    })
    .join("\n");

const css = `/* Generated by packages/ui/scripts/build-tokens.mjs from docs/design/H_handoff/tokens.json v${tokens.version}. Do not edit. */
:root {
${block(tokens.themes.light)}
  --n-ol: ${tokens.illustration.outline};
  --n-violet: #9B7BFF;
  --n-focus: ${tokens.focus.ring.split(" ").pop()};
  color-scheme: light;
}

[data-theme="dark"] {
${block(tokens.themes.dark)}
  --n-focus: ${tokens.themes.dark.acc};
  color-scheme: dark;
}
`;
writeFileSync(join(root, "packages/ui/src/tokens.css"), css);
console.log("tokens.css written from tokens.json v" + tokens.version);
